#!/usr/bin/env python3
"""Builds src/web/page.h (the gzip byte array the device serves) from src/web/page.html.

    python3 tools/gen_page.py            # rewrite page.h
    python3 tools/gen_page.py --check    # exit 1 if page.h is out of date

Edit src/web/page.html, never page.h. The test in tools/test_web_pages.py fails when
the two disagree.
"""

import gzip
import pathlib
import re
import sys
import zlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
HTML = ROOT / "src/web/page.html"
HEADER = ROOT / "src/web/page.h"

TEMPLATE = """// HTML: {html} bytes  gzip: {gz} bytes
#pragma once
// Generated by tools/gen_page.py from src/web/page.html: edit that file, not this one.
// Dashboard single page (served from flash, gzip-compressed). Security rules for the page:
//  - never put server data into innerHTML: build nodes, set textContent/value
//  - every change is a POST through api(), which adds X-Requested-With: adblock
//  - no external resources: the CSP only allows this device and the update site

namespace web {{

// {gz} bytes (gzip -9 of {html}-byte HTML)
constexpr size_t kPageGzLen = {gz};
const uint8_t kPageGz[] PROGMEM = {{
{body}
}};

}}  // namespace web
"""


def pack(html: bytes) -> bytes:
    return gzip.compress(html, compresslevel=9, mtime=0)


def render(html: bytes) -> str:
    gz = pack(html)
    rows = []
    for i in range(0, len(gz), 16):
        rows.append("  " + ", ".join(f"0x{b:02x}" for b in gz[i : i + 16]))
    return TEMPLATE.format(html=len(html), gz=len(gz), body=",\n".join(rows))


def embedded_html(header: str) -> bytes:
    body = header.split("kPageGz[] PROGMEM = {", 1)[1].split("};", 1)[0]
    data = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", body))
    return zlib.decompress(data, 31)


def main() -> int:
    html = HTML.read_bytes()
    if "--check" in sys.argv:
        try:
            ok = embedded_html(HEADER.read_text()) == html
        except (IndexError, ValueError, zlib.error):
            ok = False
        if not ok:
            print("src/web/page.h is out of date: run python3 tools/gen_page.py")
        return 0 if ok else 1
    HEADER.write_text(render(html))
    print(f"page.h: {len(html)} bytes HTML -> {len(pack(html))} bytes gzip")
    return 0


if __name__ == "__main__":
    sys.exit(main())
